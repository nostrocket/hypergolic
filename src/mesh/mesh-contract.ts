import type {NostrEvent} from 'nostr-tools/pure';
import {parseQueryFilters, verifyQueryEvent, type QueryFilter} from '../network/relay-query-contract.ts';
import {routingRecord} from '../routing/routing-contract.ts';
import {utf8Bytes} from '../storage/codec.ts';

/** NAP-MESH bf9a472; these selected bounds confer no grant, pairing or signing authority. */
export const MESH_LIMITS = Object.freeze({publishTtl: 2, subscribeTtl: 1, incomingTtl: 2,
  eventBytes: 8192, requestBytes: 8192, filters: 4, hashes: 64, tags: 256, tagFields: 64,
  identifierBytes: 128, errorBytes: 512});
export type MeshCaps = Readonly<{publishTtl: number; subscribeTtl: number}>;
export const MESH_DEFAULT_CAPS: MeshCaps = Object.freeze({publishTtl: MESH_LIMITS.publishTtl, subscribeTtl: MESH_LIMITS.subscribeTtl});
/** created_at is captured provenance only: native MUST replace it, and owns author/id/sig. */
export type MeshTemplate = Readonly<{kind: number; content: string; tags: readonly (readonly string[])[]; created_at?: number}>;
export type MeshInfoRequest = Readonly<{type: 'mesh.info'; id: string}>;
export type MeshPublishRequest = Readonly<{type: 'mesh.publish'; id: string; event: MeshTemplate; ttl: number}>;
export type MeshSubscribeRequest = Readonly<{type: 'mesh.subscribe'; id: string; subId: string; filters: readonly QueryFilter[]; ttl: number}>;
export type MeshBlobsRequest = Readonly<{type: 'mesh.blobs'; id: string; hashes: readonly string[]}>;
export type MeshCloseRequest = Readonly<{type: 'mesh.close'; subId: string}>;
export type MeshRequest = MeshInfoRequest | MeshPublishRequest | MeshSubscribeRequest | MeshBlobsRequest | MeshCloseRequest;
export type MeshFailure = Readonly<{type: 'mesh.info.result' | 'mesh.subscribe.result' | 'mesh.blobs.result'; id: string; error: string}>
  | Readonly<{type: 'mesh.publish.result'; id: string; ok: false; error: string}>;
export type MeshResult = MeshFailure
  | Readonly<{type: 'mesh.info.result'; id: string; online: boolean; peers: number; limits: MeshCaps}>
  | Readonly<{type: 'mesh.publish.result'; id: string; ok: true; event: NostrEvent; eventId: string; ttl: number}>
  | Readonly<{type: 'mesh.blobs.result'; id: string; peers: number; blobs: Readonly<Record<string, number>>}>;
/** Default-off resource sidecars are not generated by this selected Mesh profile. */
export type MeshDelivery = Readonly<{type: 'mesh.event'; subId: string; result: Readonly<{event: NostrEvent}>}>
  | Readonly<{type: 'mesh.eose'; subId: string; ttl: number}>
  | Readonly<{type: 'mesh.closed'; subId: string; reason?: string}>;
export class MeshContractError extends Error {
  constructor() {super('Invalid Mesh message'); this.name = 'MeshContractError';}
}
const invalid = (): never => {throw new MeshContractError();};
function guarded<T>(read: () => T): T {try {return read();} catch {return invalid();}}
function text(value: unknown, maximum: number, nonempty = false): string {
  if (typeof value !== 'string' || value.length > maximum || (nonempty && !value.length) || utf8Bytes(value) > maximum) return invalid();
  return value;
}
function identifier(value: unknown): string {
  const result = text(value, MESH_LIMITS.identifierBytes, true);
  if (/[\u0000-\u001f\u007f-\u009f]/u.test(result)) return invalid();
  return result;
}
function integer(value: unknown, maximum = Number.MAX_SAFE_INTEGER): number {
  if (typeof value !== 'number' || !Number.isSafeInteger(value) || value < 0 || value > maximum) return invalid();
  return value;
}
function dense(input: unknown, maximum: number): readonly unknown[] {
  if (!Array.isArray(input) || Object.getPrototypeOf(input) !== Array.prototype) return invalid();
  const length = Object.getOwnPropertyDescriptor(input, 'length')?.value;
  if (!Number.isSafeInteger(length) || length < 0 || length > maximum || Reflect.ownKeys(input).length !== length + 1) return invalid();
  return Array.from({length}, (_, index) => {
    const field = Object.getOwnPropertyDescriptor(input, String(index));
    if (!field || !Object.hasOwn(field, 'value') || !field.enumerable) return invalid();
    return field.value as unknown;
  });
}
function capValues(value: MeshCaps): MeshCaps {
  const fields = routingRecord(value, ['publishTtl', 'subscribeTtl']);
  return Object.freeze({publishTtl: integer(fields.publishTtl, 255), subscribeTtl: integer(fields.subscribeTtl, 255)});
}
function ttl(value: unknown, cap: number): number {return value === undefined ? cap : Math.min(integer(value, 255), cap);}
function frameFits(value: unknown): void {if (utf8Bytes(JSON.stringify(value)) > MESH_LIMITS.eventBytes) return invalid();}
function template(input: unknown): MeshTemplate {
  const row = routingRecord(input, ['kind', 'content'], ['tags', 'created_at']);
  const kind = integer(row.kind, 65535), content = text(row.content, MESH_LIMITS.eventBytes);
  const createdAt = row.created_at === undefined ? undefined : integer(row.created_at);
  let budget = utf8Bytes(JSON.stringify(content));
  const tags = dense(row.tags === undefined ? [] : row.tags, MESH_LIMITS.tags).map(inputTag => {
    const tag = dense(inputTag, MESH_LIMITS.tagFields);
    if (!tag.length) return invalid();
    budget += 3;
    return Object.freeze(tag.map(field => {
      const item = text(field, MESH_LIMITS.eventBytes);
      budget += utf8Bytes(JSON.stringify(item)) + 1;
      if (budget > MESH_LIMITS.eventBytes) return invalid();
      return item;
    }));
  });
  const captured = Object.freeze({kind, content, tags: Object.freeze(tags), ...(createdAt === undefined ? {} : {created_at: createdAt})});
  // Reserve every shell-owned field and the longest valid native timestamp, without choosing an author/key.
  frameFits(['EVENT', {...captured, created_at: Number.MAX_SAFE_INTEGER, id: '0'.repeat(64), pubkey: '0'.repeat(64), sig: '0'.repeat(128)}]);
  return captured;
}
function filters(input: unknown): readonly QueryFilter[] {
  const list = Array.isArray(input) ? dense(input, MESH_LIMITS.filters) : [input];
  const fields = ['ids', 'authors', 'kinds', 'since', 'until', 'limit', ...Array.from('abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ', letter => '#' + letter)];
  const values = list.map(value => {
    const row = routingRecord(value, [], fields);
    return Object.fromEntries(Object.entries(row).map(([key, item]) => [key, Array.isArray(item) ? dense(item, 64) : item]));
  });
  return parseQueryFilters(values, 32, MESH_LIMITS.filters);
}
const capturedRequests = new WeakSet<object>();
function captured(request: MeshRequest): void {if (!capturedRequests.has(request)) return invalid();}
/** Capture before await. Numeric limits/field lists come from the existing NIP-01 validator. */
export function parseMeshRequest(input: unknown, caps: MeshCaps = MESH_DEFAULT_CAPS): MeshRequest {
  return guarded(() => {
    // Read discriminant through a data descriptor, never a caller getter.
    const descriptor = input && typeof input === 'object' ? Object.getOwnPropertyDescriptor(input, 'type') : undefined;
    const type = descriptor && Object.hasOwn(descriptor, 'value') ? descriptor.value : undefined;
    let request: MeshRequest;
    if (type === 'mesh.close') {
      const row = routingRecord(input, ['type', 'subId']);
      request = Object.freeze({type, subId: identifier(row.subId)});
    } else if (type === 'mesh.info') {
      const row = routingRecord(input, ['type', 'id']); request = Object.freeze({type, id: identifier(row.id)});
    } else if (type === 'mesh.publish') {
      const row = routingRecord(input, ['type', 'id', 'event'], ['ttl']);
      request = Object.freeze({type, id: identifier(row.id), event: template(row.event), ttl: ttl(row.ttl, capValues(caps).publishTtl)});
    } else if (type === 'mesh.subscribe') {
      const row = routingRecord(input, ['type', 'id', 'subId', 'filters'], ['ttl']);
      request = Object.freeze({type, id: identifier(row.id), subId: identifier(row.subId), filters: filters(row.filters), ttl: ttl(row.ttl, capValues(caps).subscribeTtl)});
    } else if (type === 'mesh.blobs') {
      const row = routingRecord(input, ['type', 'id', 'hashes']);
      const hashes = dense(row.hashes, MESH_LIMITS.hashes).map(hash => {
        if (typeof hash !== 'string' || !/^[0-9a-fA-F]{64}$/.test(hash)) return invalid();
        return hash.toLowerCase();
      });
      request = Object.freeze({type, id: identifier(row.id), hashes: Object.freeze([...new Set(hashes)])});
    } else return invalid();
    if (utf8Bytes(JSON.stringify(request)) > MESH_LIMITS.requestBytes) return invalid();
    capturedRequests.add(request); return request;
  });
}
/** A malformed payload can still receive a correlated refusal. No invented ID/close acknowledgement. */
export function meshFailure(input: unknown, error: string): MeshFailure | null {
  try {
    if (!input || typeof input !== 'object' || Array.isArray(input) || Object.getPrototypeOf(input) !== Object.prototype) return null;
    const type = Object.getOwnPropertyDescriptor(input, 'type'), id = Object.getOwnPropertyDescriptor(input, 'id');
    if (!type || !id || !Object.hasOwn(type, 'value') || !Object.hasOwn(id, 'value') ||
      !['mesh.info', 'mesh.publish', 'mesh.subscribe', 'mesh.blobs'].includes(type.value)) return null;
    const correlation = identifier(id.value), message = text(error, MESH_LIMITS.errorBytes, true);
    return Object.freeze({type: `${type.value}.result`, id: correlation, ...(type.value === 'mesh.publish' ? {ok: false as const} : {}), error: message}) as MeshFailure;
  } catch {return null;}
}
function signedEvent(input: unknown, filters: readonly QueryFilter[], phase: 'stored' | 'live'): NostrEvent {
  const fields = routingRecord(input, ['id', 'pubkey', 'created_at', 'kind', 'content', 'tags', 'sig']);
  const tags = dense(fields.tags, MESH_LIMITS.tags).map(tag => dense(tag, MESH_LIMITS.tagFields).map(field => {
    if (typeof field !== 'string') return invalid(); return field;
  }));
  const event = verifyQueryEvent({...fields, tags}, filters, phase);
  frameFits(['EVENT', event]); return event;
}
function response(input: unknown, request: Exclude<MeshRequest, MeshCloseRequest>, author?: string): MeshResult {
  const row = routingRecord(input, ['type', 'id'], ['error', 'ok', 'event', 'eventId', 'ttl', 'online', 'peers', 'limits', 'blobs']);
  if (row.type !== `${request.type}.result` || row.id !== request.id) return invalid();
  if (row.error !== undefined) {
    const failure = meshFailure(request, text(row.error, MESH_LIMITS.errorBytes, true));
    if (!failure) return invalid();
    const allowed = request.type === 'mesh.publish' ? ['type', 'id', 'ok', 'error'] : ['type', 'id', 'error'];
    routingRecord(row, allowed);
    if (request.type === 'mesh.publish' && row.ok !== false) return invalid();
    return failure;
  }
  if (request.type === 'mesh.info') {
    routingRecord(row, ['type', 'id', 'online', 'peers', 'limits']);
    if (typeof row.online !== 'boolean') return invalid();
    const peers = integer(row.peers); if (!row.online && peers !== 0) return invalid();
    return Object.freeze({type: 'mesh.info.result', id: request.id, online: row.online, peers, limits: capValues(row.limits as MeshCaps)});
  }
  if (request.type === 'mesh.publish') {
    routingRecord(row, ['type', 'id', 'ok', 'event', 'eventId', 'ttl']);
    const event = signedEvent(row.event, Object.freeze([Object.freeze({kinds: Object.freeze([request.event.kind])})]), 'live');
    if (row.ok !== true || event.pubkey !== author || row.eventId !== event.id || row.ttl !== request.ttl ||
      event.content !== request.event.content || JSON.stringify(event.tags) !== JSON.stringify(request.event.tags)) return invalid();
    return Object.freeze({type: 'mesh.publish.result', id: request.id, ok: true, event, eventId: event.id, ttl: request.ttl});
  }
  if (request.type !== 'mesh.blobs') return invalid(); // subscribe has refusal only, never an opened result.
  routingRecord(row, ['type', 'id', 'peers', 'blobs']);
  const peers = integer(row.peers), values = routingRecord(row.blobs, request.hashes);
  const blobs = Object.fromEntries(request.hashes.map(hash => [hash, integer(values[hash], peers)]));
  return Object.freeze({type: 'mesh.blobs.result', id: request.id, peers, blobs: Object.freeze(blobs)});
}
/** Verify exact native correlation/shapes; never turn malformed success into fabricated empty data. */
export function captureMeshResult(input: unknown, request: MeshRequest, expectedAuthor?: string): MeshResult {
  return guarded(() => {captured(request); if (request.type === 'mesh.close') return invalid(); return response(input, request, expectedAuthor);});
}
/** Subscription lifetime/one EOSE/per-sub dedup remain stateful owner duties; this only captures/validates wire bytes. */
export function captureMeshDelivery(input: unknown, subscription: MeshSubscribeRequest, phase: 'stored' | 'live' = 'live'): MeshDelivery {
  return guarded(() => {
    captured(subscription);
    if (subscription.type !== 'mesh.subscribe' || (phase !== 'stored' && phase !== 'live')) return invalid();
    const row = routingRecord(input, ['type', 'subId'], ['result', 'ttl', 'reason']);
    if (row.subId !== subscription.subId) return invalid();
    if (row.type === 'mesh.event') {
      routingRecord(row, ['type', 'subId', 'result']); const result = routingRecord(row.result, ['event']);
      return Object.freeze({type: 'mesh.event', subId: subscription.subId, result: Object.freeze({event: signedEvent(result.event, subscription.filters, phase)})});
    }
    if (row.type === 'mesh.eose') {
      routingRecord(row, ['type', 'subId', 'ttl']); if (row.ttl !== subscription.ttl) return invalid();
      return Object.freeze({type: 'mesh.eose', subId: subscription.subId, ttl: subscription.ttl});
    }
    if (row.type !== 'mesh.closed') return invalid();
    routingRecord(row, ['type', 'subId'], ['reason']);
    return Object.freeze({type: 'mesh.closed', subId: subscription.subId,
      ...(row.reason === undefined ? {} : {reason: text(row.reason, MESH_LIMITS.errorBytes)})});
  });
}
